"""Generate independent reference values for the Java core tests.

The output CSV files are committed under core/src/test/resources/reference/,
so the Java tests (and CI) do not need Python. Re-run this script to
reproduce or extend the references:

    python3 -m venv .venv && .venv/bin/pip install -r requirements.txt
    .venv/bin/python generate_references.py
"""

import csv
import itertools
from pathlib import Path

import numpy as np
import scipy
from scipy.special import exp1

OUT_DIR = Path(__file__).resolve().parents[2] / "core/src/test/resources/reference"
SECONDS_PER_DAY = 86_400.0
SECONDS_PER_YEAR = 365.0 * SECONDS_PER_DAY


def header(f, description: str) -> None:
    f.write(f"# {description}\n")
    f.write(f"# Generated by tools/validation/generate_references.py "
            f"(numpy {np.__version__}, scipy {scipy.__version__})\n")


def write_e1() -> None:
    # Log-spaced over [1e-6, 50] plus points around the series/continued-fraction
    # switch at x = 1, where an implementation is most likely to be inaccurate.
    xs = np.concatenate([
        np.logspace(-6, np.log10(50.0), 200),
        [0.5, 0.999, 1.0, 1.001, 2.0, 10.0],
    ])
    xs = np.unique(xs)
    path = OUT_DIR / "e1_scipy.csv"
    with path.open("w", newline="") as f:
        header(f, "x, E1(x) from scipy.special.exp1")
        w = csv.writer(f)
        w.writerow(["x", "e1"])
        for x in xs:
            w.writerow([repr(float(x)), repr(float(exp1(x)))])
    print(f"wrote {len(xs)} rows to {path}")


def write_line_source() -> None:
    """Infinite line source (Kelvin) with constant heat extraction q.

    dT(r, t) = q / (4 pi lambda) * E1(r^2 / (4 alpha t)),  alpha = lambda / rho_c
    T_f(t)   = T0 - q * (R_b + 1 / (4 pi lambda) * E1(r_b^2 / (4 alpha t)))
    """
    conductivities = [2.5, 3.0, 4.0]                        # W/(m K)
    heat_rates = [20.0, 35.0]                               # W/m
    times = [3600.0, 30 * SECONDS_PER_DAY, 25 * SECONDS_PER_YEAR]  # s
    radii = [0.0575, 1.0]                                   # m
    rho_c = 2.2e6                                           # J/(m^3 K)
    t0 = 7.5                                                # degC
    r_b_resistance = 0.10                                   # m K/W

    path = OUT_DIR / "line_source_scipy.csv"
    rows = 0
    with path.open("w", newline="") as f:
        header(f, "Kelvin line source; rho_c=2.2e6 J/(m3 K), T0=7.5 degC, "
                  "Rb=0.10 m K/W. fluid_temp_c treats r_m as the borehole radius")
        w = csv.writer(f)
        w.writerow(["conductivity_w_per_mk", "volumetric_heat_capacity_j_per_m3k",
                    "q_w_per_m", "r_m", "t_s", "delta_t_k",
                    "undisturbed_temp_c", "borehole_resistance_mk_per_w", "fluid_temp_c"])
        for lam, q, t, r in itertools.product(conductivities, heat_rates, times, radii):
            alpha = lam / rho_c
            g = exp1(r * r / (4.0 * alpha * t)) / (4.0 * np.pi * lam)
            delta_t = q * g
            fluid = t0 - q * (r_b_resistance + g)
            w.writerow([repr(v) for v in (lam, rho_c, q, r, t, float(delta_t),
                                          t0, r_b_resistance, float(fluid))])
            rows += 1
    print(f"wrote {rows} rows to {path}")


# Monthly mean air temperature [degC], Bergen - Florida (SN50540), normal period 1991-2020.
# Source: Norwegian Centre for Climate Services, seklima.met.no.
# Verified against seKlima on 2026-10-29 (deviation < 0.2 degC), see docs/model.md section 3.2.
BERGEN_NORMALS_1991_2020_C = [2.6, 2.4, 3.8, 6.7, 10.1, 13.0, 15.3, 15.1, 12.3, 8.6, 5.4, 3.1]
DAYS_PER_MONTH = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
DEGREE_DAY_BASE_C = 17.0


def degree_day_fractions(normals_c, base_c=DEGREE_DAY_BASE_C):
    """Share of annual heating degree days per month: days * max(0, base - T_month) / sum."""
    dd = [d * max(0.0, base_c - t) for d, t in zip(DAYS_PER_MONTH, normals_c)]
    total = sum(dd)
    return [x / total for x in dd]


def print_bergen_profile() -> None:
    fractions = degree_day_fractions(BERGEN_NORMALS_1991_2020_C)
    print("Bergen degree-day profile (base 17 degC), paste into MonthlyProfile.bergenDegreeDays():")
    print("    " + ", ".join(f"{f:.9f}" for f in fractions))
    print(f"    sum = {sum(fractions):.12f}")


HOURS_PER_MONTH = 8760.0 / 12
SECONDS_PER_MONTH = HOURS_PER_MONTH * 3600.0
PEAK_SECONDS = 6 * 3600.0

# (name, annual heat kWh, peak heat kW, SCOP, COP_peak, lambda, rho_c, T0, r_b, R_b, T_min, years)
SIZING_SCENARIOS = [
    ("house_bergen", 20_000.0, 8.0, 3.5, 3.0, 3.0, 2.2e6, 7.5, 0.0575, 0.10, -3.0, 25),
    ("poor_rock_high_load", 35_000.0, 14.0, 3.2, 2.8, 2.5, 2.2e6, 6.5, 0.0575, 0.12, -3.0, 25),
    ("large_house", 45_000.0, 12.0, 4.0, 3.2, 3.0, 2.2e6, 7.5, 0.0575, 0.08, -3.0, 25),
    ("house_ten_years", 20_000.0, 8.0, 3.5, 3.0, 3.0, 2.2e6, 7.5, 0.0575, 0.10, -3.0, 10),
]


def load_schedule(annual_kwh, peak_kw, scop, cop_peak, years, fractions):
    """Monthly steps (730 h) plus a 6-hour peak at the end of the coldest month of the last year.

    The peak power is max(monthly mean, design ground power): it replaces the mean, it is not added.
    """
    ground_kwh = annual_kwh * (1.0 - 1.0 / scop)
    peak_w = peak_kw * 1000.0 * (1.0 - 1.0 / cop_peak)
    coldest = int(np.argmax(fractions))
    starts, powers = [], []
    for year in range(years):
        for month in range(12):
            start = (year * 12 + month) * SECONDS_PER_MONTH
            power = ground_kwh * fractions[month] * 3.6e6 / SECONDS_PER_MONTH
            starts.append(start)
            powers.append(power)
            if year == years - 1 and month == coldest:
                starts.append(start + SECONDS_PER_MONTH - PEAK_SECONDS)
                powers.append(max(power, peak_w))
    return np.array(starts), np.array(powers), years * 12 * SECONDS_PER_MONTH


def closed_form_depth(starts, powers, end, lam, rho_c, r_b, res_b, t0, t_min):
    """H = max over step ends of [Q(t) R_b + sum dQ_i G(t - t_i)] / (T0 - T_min).

    Step i is in force on (t_i, t_{i+1}], so at the end of step i only steps 0..i contribute.
    """
    alpha = lam / rho_c
    increments = np.diff(np.concatenate([[0.0], powers]))
    ends = np.append(starts[1:], end)
    load_terms = []
    for i, t in enumerate(ends):
        ages = t - starts[: i + 1]
        g = exp1(r_b * r_b / (4.0 * alpha * ages)) / (4.0 * np.pi * lam)
        load_terms.append(powers[i] * res_b + np.dot(increments[: i + 1], g))
    worst = int(np.argmax(load_terms))
    month_of_min = int(np.ceil(ends[worst] / SECONDS_PER_MONTH - 1e-9)) - 1
    return load_terms[worst] / (t0 - t_min), month_of_min


def write_sizing() -> None:
    # Same 9-decimal table as MonthlyProfile.bergenDegreeDays(), so both sides use identical fractions.
    fractions = [round(f, 9) for f in degree_day_fractions(BERGEN_NORMALS_1991_2020_C)]
    path = OUT_DIR / "sizing_scipy.csv"
    with path.open("w", newline="") as f:
        header(f, "Closed-form single borehole sizing, Bergen degree-day profile, 730 h months, 6 h peak")
        w = csv.writer(f)
        w.writerow(["name", "annual_heat_kwh", "peak_heat_kw", "scop", "cop_peak",
                    "conductivity_w_per_mk", "volumetric_heat_capacity_j_per_m3k", "undisturbed_temp_c",
                    "borehole_radius_m", "borehole_resistance_mk_per_w", "min_fluid_temp_c", "years",
                    "required_depth_m", "month_of_minimum"])
        for (name, q, p, scop, cop, lam, rho_c, t0, r_b, res_b, t_min, years) in SIZING_SCENARIOS:
            starts, powers, end = load_schedule(q, p, scop, cop, years, fractions)
            depth, month = closed_form_depth(starts, powers, end, lam, rho_c, r_b, res_b, t0, t_min)
            w.writerow([name] + [repr(float(v)) for v in (q, p, scop, cop, lam, rho_c, t0, r_b, res_b, t_min)]
                       + [years, repr(float(depth)), month])
            print(f"{name}: H = {depth:.2f} m, minimum in month {month}")
    print(f"wrote {len(SIZING_SCENARIOS)} rows to {path}")


if __name__ == "__main__":
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    write_e1()
    write_line_source()
    write_sizing()
    print_bergen_profile()
